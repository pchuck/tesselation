/// Fixed point of σ: o = τ/(1 − μ) (float; used only for window tests
/// and the preimage box chain).  ≈ (13.708, −6.882).
fn o_fix() -> Vec2 {
    let t = kv(TAU);
    let m = kv(MU);
    let dx = 1.0 - m.x;
    let dy = -m.y;
    let n = dx * dx + dy * dy;
    Vec2::new((t.x * dx + t.y * dy) / n, (t.y * dx - t.x * dy) / n)
}

