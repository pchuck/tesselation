/// Frame exponent Ψ of a BOW/HEX cluster (DEC expands through pose 0).
/// Ψ_HEX(r) = (8 − 8r) mod 20 and Ψ_BOW(r) = (4 − 8r) mod 20, pinned by
/// the pose-labelled fires of the reference patch (zero conflicts).
#[inline]
fn psi_m(ty: u8, r: u8) -> usize {
    let b = if ty == TY_B { 4 } else { 8 };
    (b + 160 - 8 * r as usize) % 20
}

