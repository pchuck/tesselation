//! Andritz 10gon-3 substitution — a genuinely quasiperiodic girih tiling
//! from Leonhard Andritz's fivefold substitution family (submitted to the
//! Tilings Encyclopedia, February 2016; entry *bowtie-hexagon-10gon-3*),
//! tiles inspired by Islamic girih patterns.
//!
//! The same three unit-edge girih prototiles as
//! [`super::andritz_bowtie_hexagon_10gon_1`] — BOW, HEX and the regular
//! DEC — with a faster-inflating substitution: the σ-frame map is
//! f(z) = μ·z + τ with **μ = φ⁴·e^{72°i} = 3t² + 2t⁴ + 3t⁶**
//! (|μ| = φ⁴ = 6.854…, each generation inflated by φ⁴ and turned 72°).
//!
//! # The substitution system
//!
//! Three unit-edge girih prototiles, angles in multiples of 18°:
//!
//! * **BOW** (`TY_B`) — the concave bow-tie hexagon (area 1.31433);
//! * **HEX** (`TY_H`) — the elongated hexagon "tie" (long diagonal φ²,
//!   area 2.12663);
//! * **DEC** (`TY_D`) — the regular decagon (circumradius φ, area
//!   2.5·cot 18° = 7.69421), rotation-blind.
//!
//! Every tile at center z claims a fixed *cluster* of unit children
//! around f(z): child *j* of the parent-kind table sits at
//! f(z) + t^{Ψ}·w_j.  The cluster tables (45 BOW / 64 HEX / 136 DEC
//! slots) were mined from the decoded 957-tile reference patch by
//! union-voting the per-fire offsets over all rich fires — a slot is
//! kept only when every fire that shows it agrees on kind and rotation
//! — then **region-killed** (a slot survives only when |w|/2 ≤
//! φ⁴·circ(kind), so its child lands inside the inflated parent σ(p):
//! long-reach slots fire correctly near the reference patch by
//! accident and produce phantoms far away) and finally configuration-
//! killed against far-field overlaps.  The walk from the 21-tile seed
//! core reproduces **all 957 reconstructed tiles with exact rank-8
//! centers and orientations by level 2**, with zero false claims
//! against the decoded polygons over every decoded parent and zero
//! collisions across the 56 106 claims of levels 0–2.
//!
//! The clusters are a **shared covering**: neighbours share boundary
//! tiles (42.7 % of walk tiles are claimed by two or more parents with
//! matching kind and rotation), so the child census
//!
//! ```text
//! M = [[19,19,7],     BOW → 19 BOW + 19 HEX + 7 DEC
//!      [26,29,9],     HEX → 26 BOW + 29 HEX + 9 DEC
//!      [60,45,31]]    DEC → 60 BOW + 45 HEX + 31 DEC
//! ```
//! counts 45/64/136 slots per parent.  The tiling is generated by the
//! verified walk rather than by iterating a disjoint inflation.
//!
//! # Orientation law
//!
//! BOW/HEX carry an orientation r ∈ 0..4 (36° steps, C₂-symmetric so
//! r and r+5 agree); DEC is rotation-blind.  A parent expands its
//! cluster through frame exponent
//!
//! ```text
//! Ψ_HEX(r) = (8 − 8r) mod 20,
//! Ψ_BOW(r) = (4 − 8r) mod 20,
//! Ψ_DEC    = 0,
//! ```
//! and children take rotation r_child = (r_parent + δ_j) mod 5 per-slot
//! constants δ_j (for a DEC parent — always pose 0 — the slot value is
//! the absolute class).  The frames and all δ_j were pinned by the
//! unanimous union votes of the reference patch (zero conflicts) and
//! confirmed by the exact oriented walk below.
//!
//! # Generation for a view
//!
//! A wavefront BFS from the 21-tile seed core around the fixed point
//! o = τ/(1 − μ) grows the tiling outward; substitution level *k* covers
//! a disk of radius ≈ 3, 23, 160, 900 … (growing ×φ⁴ per level, the
//! conservative table below).  The sweep is region-filtered through the
//! σ⁻¹ preimage box chain of the view (claims land within SLOT_REACH of
//! σ(parent); σ⁻¹ = e^{−72°i}/φ⁴ rotates each chain box by −72°, so the
//! boxes are kept as axis-aligned bounding boxes as for 10gon-1),
//! keeping the work linear in the view area even far from o.  `generate`
//! BFS-iterates until the emitted patch provably covers the view
//! (clipped-area equality, as for [`super::girih_qc`]); tile emission
//! is unit-edge at every level.  Views whose far corner lies beyond the
//! level-3 covered radius (≈ 900) or whose area would exceed
//! [`MAX_TILES`] fail with a zoom-in message.

