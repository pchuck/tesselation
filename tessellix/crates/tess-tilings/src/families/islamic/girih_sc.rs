//! Girih star-and-cross, 10-fold (M35) — the periodic 10-pointed star-
//! and-cross strapwork wallpaper, reproduced as a [`LatticeTiling`] data
//! table measured from a classical reference panel.
//!
//! # Geometry
//!
//! * Lattice `a1 = (77, 45)`, `a2 = (0, 90)` (oblique, area 6930);
//!   10-pointed star centres sit on the index lattice `(i, j)`, bobbin
//!   centres at the half-lattice `(i + 1/2, j + 1/2)`-type holes.
//! * Cell `[-38.5, 38.5] x [-45, 45]` containing 545 tiles: 99 white
//!   ground faces (the 10-pointed pinwheel star, four diagonal faces,
//!   four petals, two side corridors, four corners, small squares and
//!   diamonds) and 446 ink strap pieces (the band corridors partitioned
//!   by their medial skeleton).
//! * Wallpaper group **pmm**: mirrors in the star axes x = 0 and y = 0
//!   composed with the lattice (2-fold rotations at every star and
//!   bobbin centre). The measured artwork honours the mirrors to within
//!   its own drawing tolerance (~0.01-0.02 px); tiles are grouped into
//!   `seed` classes by their D2 orbit (IoU >= 0.8 match).
//!
//! # Provenance and verification
//!
//! The tile table was measured from the reference artwork (1 px/unit)
//! by band fitting (strap families with ridge-snapped centrelines,
//! duplicate merging, cap trimming), raster clipping, and a medial-skeleton
//! partition of the ink into corridor pieces; white faces are the exact
//! complement of the emitted ink tiles. The cell was verified in exact
//! form before porting (Python, shapely):
//!
//! * sum of cell areas == |det(a1, a2)| = 6930 to 3.9e-16 (relative);
//! * every interior edge is shared by exactly 2 tiles (98 border edges
//!   once, 0 interior violations);
//! * every interior vertex angle sum == 360 degrees exactly;
//! * a fine grid over a 3x3 lattice patch is covered exactly once.

