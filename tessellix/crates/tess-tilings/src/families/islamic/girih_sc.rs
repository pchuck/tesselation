/// Cell constructor helper: one measured tile (vertex list in cell units).
fn c(seed: u32, pts: &[[f64; 2]]) -> Cell {
    Cell {
        seed,
        poly: Polygon::from_slice(
            &pts.iter()
                .map(|p| Vec2::new(p[0], p[1]))
                .collect::<Vec<_>>(),
        ),
    }
}

