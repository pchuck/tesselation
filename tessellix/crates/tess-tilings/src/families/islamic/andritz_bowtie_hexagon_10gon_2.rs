//! Andritz 10gon-2 substitution — a genuinely quasiperiodic girih tiling
//! from Leonhard Andritz's fivefold substitution family (submitted to the
//! Tilings Encyclopedia, February 2016; entry *bowtie-hexagon-10gon-2*),
//! tiles inspired by Islamic girih patterns.
//!
//! The same three unit-edge girih prototiles as
//! [`super::andritz_bowtie_hexagon_10gon_1`] — BOW, HEX and the regular
//! DEC — with a faster-inflating substitution: the σ-frame map is
//! f(z) = τ − λ·z with **λ = 3 + 2φ = 6.236…** (μ = −λ: an inflation by λ
//! composed with a half-turn) versus φ² for 10gon-1.
//!
//! # The substitution system
//!
//! Three unit-edge girih prototiles, angles in multiples of 18°:
//!
//! * **BOW** (`TY_B`) — the concave bow-tie hexagon (area 1.31433);
//! * **HEX** (`TY_H`) — the elongated hexagon "tie" (long diagonal φ²,
//!   area 2.12663);
//! * **DEC** (`TY_D`) — the regular decagon (circumradius φ, area
//!   2.5·cot 18° = 7.69421), rotation-blind.
//!
//! Every tile at center z claims a fixed *cluster* of unit children
//! around f(z): child *j* of the parent-kind table sits at
//! f(z) + t^{Ψ}·v_j.  The cluster tables (27 BOW / 38 HEX / 96 DEC
//! slots) were mined from the decoded reference patch and verified
//! slot-for-slot: the walk reproduces **all 691 reconstructed tiles
//! with exact rank-8 centers and orientations by level 2, with zero
//! false claims inside the raster window and zero kind/rotation
//! collisions through level 3**.
//!
//! Unlike 10gon-1 the clusters are **not disjoint**: neighbours share
//! boundary tiles (13 % of walk tiles are claimed by two parents with
//! matching kind and rotation), so the child census
//!
//! ```text
//! M = [[11,14,2],    BOW → 11 BOW + 14 HEX + 2 DEC
//!      [12,22,4],    HEX → 12 BOW + 22 HEX + 4 DEC
//!      [35,35,26]]   DEC → 35 BOW + 35 HEX + 26 DEC
//! ```
//! has Perron root 43.151 — the per-level growth of the walk (measured
//! 29 690/711 = 41.8 from the seed) — while cluster areas exceed
//! λ²·A(parent) by 7–17 %, exactly the shared tiles.  The tiling is
//! therefore generated by the verified walk rather than by iterating a
//! disjoint inflation.
//!
//! # Orientation law
//!
//! BOW/HEX carry an orientation r ∈ 0..4 (36° steps, C₂-symmetric so
//! r and r+5 agree); DEC is rotation-blind.  A parent expands its
//! cluster through frame exponent
//!
//! ```text
//! Ψ_BOW(r) = 2r + 5 + 10·[(2r mod 5) ≥ 3]  (mod 20),
//! Ψ_HEX(r) = 2r + 10·[(2r mod 5) ≥ 3]      (mod 20),
//! Ψ_DEC    = 1,
//! ```
//! and children take rotation r_child = (r_parent + δ_j) mod 5 per-slot
//! constants δ_j (for a DEC parent the slot value is the absolute class;
//! the DEC cluster is t⁴-symmetric as a (kind, offset) set, so the pose
//! 1 expansion is positionally canonical).  The frames t^{Ψ} and all δ_j
//! were fitted from the 18 pose-informative clusters of the reference
//! patch (zero conflicts across frames sharing slots) and confirmed by
//! the exact oriented walk below.
//!
//! # Generation for a view
//!
//! A wavefront BFS from the 13-tile seed core around the fixed point
//! o = τ/(1 − μ) grows the tiling outward; substitution level *k* covers
//! a disk of radius ≈ 3, 20, 58, … (growing ×λ per level, the
//! conservative table below).  The sweep is region-filtered through the
//! σ⁻¹ preimage box chain of the view (claims land within SLOT_REACH of
//! σ(parent); σ⁻¹ = −1/λ is a pure contraction with a half-turn, so the
//! chain boxes stay axis-aligned), keeping the work linear in the view
//! area even far from o.  `generate` BFS-iterates until the emitted
//! patch provably covers the view (clipped-area equality, as for
//! [`super::girih_qc`]); tile emission is unit-edge at every level.
//! Views whose far corner lies beyond the level-4 covered radius
//! (≈ 460) or whose area would exceed [`MAX_TILES`] fail with a zoom-in
//! message.

