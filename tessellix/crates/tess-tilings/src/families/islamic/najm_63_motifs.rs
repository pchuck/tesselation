//! Kaplan §3.5 design-element motifs on the Najm ([6,3]; 2e, 0, 3e; AC)
//! substrate.
//!
//! The substrate is the registered [`super::najm::najm_63_2e_0_3e_ac`]
//! table reused verbatim (its six cell polygons — dodecagon, two
//! enneagons, three concave bowties — are the motif tiles, bit-identical
//! to the landed substrate). Per-tile motif assignment:
//!
//! * dodecagon — [`Motif::Rosette`] at the ideal angle θ = π/12 = 15°
//!   (`h = 1`, `phi = 0`), depth `s = 3`: 48 segments, 13 faces —
//!   12 hexagonal petals + one 48-gon core;
//! * each enneagon — [`Motif::Star`] at θ = 35°, depth `s = 2`:
//!   18 segments, 10 faces — 9 quads + one 18-gon star-polygon core.
//!   θ = 35° (not the ideal 20°) because the ideal-angle s = 1 star is
//!   a shallow near-invisible rim band and θ = 40° produces collinear
//!   overlapping arms (engine-hostile); 35° at depth 2 is measured
//!   collinear-overlap-free and gives a clean deep 18-pointed ring;
//! * the three bowties — `None`: they keep their plain outline as a
//!   single face (the `Motif::None` path of the assignment API).
//!
//! 36 cells per ⟨(√3, 0), (√3/2, 3/2)⟩ cell, Σ areas = |det| exact.
//! Wallpaper group p6m: verified on the torus segment multiset of a
//! ±2-cell window — rot60 and rot120 about the dodecagon centre and
//! the mirrors through it at 0° and 30° hold exactly, while rot60
//! about the enneagon centre and half-lattice translations fail as
//! expected (motif battery kaplan-22a, `final_out.txt`).

