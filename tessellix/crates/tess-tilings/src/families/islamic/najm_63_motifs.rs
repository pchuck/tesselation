/// Per-tile motif assignment over the Najm substrate cells (dodecagon,
/// enneagon ×2, bowtie ×3).
pub(crate) fn motifs() -> Vec<Option<Motif>> {
    vec![
        Some(Motif::Rosette {
            n: 12,
            theta_deg: 15.0,
            s: 3,
            h: 1.0,
            phi_deg: 0.0,
        }),
        Some(Motif::Star {
            n: 9,
            theta_deg: 35.0,
            s: 2,
        }),
        Some(Motif::Star {
            n: 9,
            theta_deg: 35.0,
            s: 2,
        }),
        None,
        None,
        None,
    ]
}

/// The motif-free Najm substrate tiles, in cell order (borrowed
/// through a fresh substrate build).
pub(crate) fn substrate_tiles(base: &LatticeTiling) -> Vec<&[Vec2]> {
    base.cells.iter().map(|c| c.poly.pts.as_slice()).collect()
}

