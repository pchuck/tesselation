/// Hankin §3.5 motif plate on the Najm [6,3] template substrate.
pub fn najm_63_motifs() -> LatticeTiling {
    let base = super::najm::najm_63_2e_0_3e_ac();
    let tiles = substrate_tiles(&base);
    let mut it = tiles.iter();
    let dodecagon = it.next().expect("dodecagon cell");
    let enne0 = it.next().expect("first enneagon cell");
    let enne1 = it.next().expect("second enneagon cell");
    debug_assert_eq!(dodecagon.len(), 12, "substrate cell 0 is the dodecagon");
    debug_assert_eq!(enne0.len(), 9, "substrate cell 1 is an enneagon");
    debug_assert_eq!(enne1.len(), 9, "substrate cell 2 is an enneagon");
    debug_assert!(it.all(|b| b.len() == 6), "remaining cells are bowties");
    let (cells, report) = build_cells_with_motifs(&tiles, &motifs());
    debug_assert!(report.complete, "motif figures incomplete");
    debug_assert!(
        report.per_tile.iter().all(|t| (t.area_sum - t.tile_area).abs() < 1e-9),
        "face partition inexact"
    );
    LatticeTiling {
        id: "najm-63-motifs",
        name: "Najm motif plate ([6,3]; 2e, 0, 3e; AC)",
        description: "Kaplan §3.5 design-element motifs on the Najm [6,3]; 2e, 0, 3e (AC) substrate (diss. §3.6.1 Fig. 3.21, table reused from najm-63-2e-0-3e-ac): ideal rosette theta = 15 degrees depth s = 3 on the dodecagon (12 hexagonal petals + 48-gon core), 18-point star ring theta = 35 degrees depth s = 2 on each enneagon (9 quads + 18-gon core), plain bowties as Motif::None single faces; 36 cells per <(sqrt(3),0),(sqrt(3)/2,3/2)> cell, wallpaper group p6m.",
        lattice: base.lattice,
        cells,
        offset: Vec2::ZERO,
        group: WallpaperGroup::P6m,
        lattice_kind: LatticeKind::Hexagonal,
        category: TilingCategory::Islamic,
        secondary: &[],
        seed_pattern: SeedPattern::Uniform,
        params: &SIMILARITY_PARAMS,
        make_map: similarity_map,
        color_mode: ColorMode::Pattern,
    }
}
