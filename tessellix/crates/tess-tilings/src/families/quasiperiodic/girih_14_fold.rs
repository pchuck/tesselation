/// A placed tile instance: class, dihedral orientation (J = rotation
/// class 0..13 in π/7 units, M = mirror flag), exact anchor twist, and
/// the level (world scale = λ^level).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Inst {
    cls: u8,
    j: u8,
    m: bool,
    t: Tw,
    level: u8,
}

/// Substitute one parent (level ≥ 1) into its certified kid panel —
/// corner kids, then edge kids, then interior kids (the JSON
/// `build_panels` order; counts and vertex sets are order-independent,
/// determinism needs only a fixed order). Exact transports (brief
/// §Generation; `girih_core.subst` ground truth):
/// corner kid i:
///   (G14, J_p, M_p, t_p + λ^level·g_p(CV[i]) − λ^(level−1)·g_p(CG), level−1)
/// rule kid (j, m, t_k):
///   (kid, (J_p ± j) mod 14, M_p ⊕ m, t_p + λ^(level−1)·g_p(t_k), level−1)
/// with the rotation sign flipped under the parent mirror. Kids are
/// emitted whole; shared corner/edge kids dedup later by exact vertex
/// set.
fn subst(par: &Inst, t: &Tables, out: &mut Vec<Inst>) {
    debug_assert!(par.level >= 1, "subst below level 0");
    let cls = par.cls as usize;
    let nv = NV[cls];
    let s = t.lam_pow[par.level as usize];
    let s2 = t.lam_pow[par.level as usize - 1];
    let gp = |z: Tw| -> Tw { g_apply(par.j as usize, par.m, z) };
    // corner kids (class G14, same dihedral as the parent)
    let gp_cg = gp(t.cg);
    for i in 0..nv {
        let wvi = par.t.add(s.tmul(gp(t.cv[cls][i])));
        let t2 = wvi.sub(s2.tmul(gp_cg));
        out.push(Inst {
            cls: 10,
            j: par.j,
            m: par.m,
            t: t2,
            level: par.level - 1,
        });
    }
    // edge + interior kids (RULES[cls] = nv edge entries, then interior)
    for e in RULES[cls].iter() {
        let tk = Tw::new(K7([e[3], e[4], e[5]]), K7([e[6], e[7], e[8]]), 1);
        let j = e[1] as i64;
        let j2 = (par.j as i64 + if par.m { -j } else { j }).rem_euclid(14) as u8;
        let t2 = par.t.add(s2.tmul(gp(tk)));
        out.push(Inst {
            cls: e[0] as u8,
            j: j2,
            m: par.m != (e[2] != 0),
            t: t2,
            level: par.level - 1,
        });
    }
}

/// World vertex ring of an instance (exact).
fn verts_of(inst: &Inst, t: &Tables) -> Vec<Tw> {
    let cv = &t.cv[inst.cls as usize];
    let s = t.lam_pow[inst.level as usize];
    cv.iter()
        .map(|w| inst.t.add(s.tmul(g_apply(inst.j as usize, inst.m, *w))))
        .collect()
}

/// Exact insertion-ordered dedup: a kid duplicates an earlier one iff
/// class and sorted canonical vertex keys coincide (whole-kid placement
/// equality; valid at every level because panel tilings are exact and
/// the shared corner/edge kids are bit-identical across incident
/// parents).
fn dedup(kids: Vec<Inst>, t: &Tables) -> Vec<Inst> {
    let mut seen: HashSet<(usize, Vec<TKey>)> = HashSet::new();
    let mut out = Vec::with_capacity(kids.len());
    for k in kids {
        let mut keys: Vec<TKey> = verts_of(&k, t).iter().map(|w| w.key()).collect();
        keys.sort();
        if seen.insert((k.cls as usize, keys)) {
            out.push(k);
        }
    }
    out
}

/// f64 AABB of an instance's world ring.
fn aabb_of(inst: &Inst, t: &Tables) -> BBox {
    let mut x0 = f64::MAX;
    let mut y0 = f64::MAX;
    let mut x1 = f64::MIN;
    let mut y1 = f64::MIN;
    for w in verts_of(inst, t) {
        let p = w.vec2();
        x0 = x0.min(p.x);
        y0 = y0.min(p.y);
        x1 = x1.max(p.x);
        y1 = y1.max(p.y);
    }
    BBox::new(Vec2::new(x0, y0), Vec2::new(x1, y1))
}

/// Culling pad at level k: a kid's descendants reach beyond the kid
/// polygon by at most pad(k) = pad_unit·Σ_{i<k} λ^i (induction on the
/// certified panel closure; see the module doc and brief §Generation).
fn pad_for(level: u8, t: &Tables) -> f64 {
    let mut acc = 0.0;
    let mut p = 1.0;
    for _ in 0..level {
        acc += p;
        p *= t.lam_f;
    }
    t.pad_unit * acc
}

