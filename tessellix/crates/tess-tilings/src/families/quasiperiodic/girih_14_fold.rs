/// Point-to-segment distance (f64; δ_v measurement only).
fn seg_dist(p: Vec2, a: Vec2, b: Vec2) -> f64 {
    let abx = b.x - a.x;
    let aby = b.y - a.y;
    let apx = p.x - a.x;
    let apy = p.y - a.y;
    let t = ((apx * abx + apy * aby) / (abx * abx + aby * aby)).clamp(0.0, 1.0);
    let dx = apx - t * abx;
    let dy = apy - t * aby;
    (dx * dx + dy * dy).sqrt()
}

