/// Float value of sin(π/7) = √((2−b)/4) — emission/geometry and test
/// floats only (all correctness comparisons are exact K₇/`Tw` tuple
/// tests). NOTE: `glb_binary_n7.rs` carries an `S1` literal that is
/// *not* sin(π/7) (it differs in the 9th decimal from that file's own
/// stated intent) — a latent quirk there; do not copy it.
const S1_F: f64 = 0.433_883_739_117_558_1;

/// Cap on the seed-fit level (λ⁹ ≈ 4.3e7 inradius units — far beyond any
/// float-sane view; the area pre-guard refuses much earlier).
const N_MAX: u8 = 9;

/// Bound on normalized dyadic exponents (module elements normalize to
/// e ≤ 1; slack covers `tmul` intermediates).
const SCALE_E_MAX: i32 = 6;
/// Bound on normalized Z[b] coefficients (worst measured intermediate
/// ~4.3e9 at the N_MAX seed — far under the i64 product limits).
const COEF_MAX: i64 = 1 << 40;

/// Canonical key tuple of a normalized twist ([`Tw::key`]).
type TKey = ([i64; 3], [i64; 3], i32);

/// An exact twist point/vector: physical (x, y) = (val(k₁), S1_F·val(k₂))
/// divided by 2^e, with (k₁, k₂) ∈ K₇² — i.e. z = val(k₁) +
/// i·sin(π/7)·val(k₂) scaled by 2⁻e, a point of the module ½Z[ζ₁₄] in
/// dyadic form. Normalized (via [`Tw::new`]): e minimal — the
/// coefficients are not all even (zero kept at e = 0) — so two `Tw` are
/// equal exactly when their physical points are equal, and `key()` is a
/// canonical dedup key.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
struct Tw {
    k1: K7,
    k2: K7,
    e: i32,
}

impl Tw {
    /// Normalizing constructor: divides out common powers of two while
    /// `e > 0` and all six coefficients are even (zero kept at e = 0).
    fn new(k1: K7, k2: K7, e: i32) -> Tw {
        let mut t = Tw { k1, k2, e };
        if t.k1.is_zero() && t.k2.is_zero() {
            return Tw {
                k1: K7::ZERO,
                k2: K7::ZERO,
                e: 0,
            };
        }
        while t.e > 0 && t.k1.0.iter().chain(t.k2.0.iter()).all(|c| c % 2 == 0) {
            for c in t.k1.0.iter_mut() {
                *c /= 2;
            }
            for c in t.k2.0.iter_mut() {
                *c /= 2;
            }
            t.e -= 1;
        }
        debug_assert!(
            t.e >= 0
                && t.e <= SCALE_E_MAX
                && t.k1.0.iter().chain(t.k2.0.iter()).all(|c| c.abs() < COEF_MAX),
            "twist coefficients out of bound: {t:?}"
        );
        t
    }

    /// Exact zero test.
    fn is_zero(self) -> bool {
        self.k1.is_zero() && self.k2.is_zero()
    }

    /// Scale the coefficients up to exponent `e` (≥ self.e) — exact.
    fn align(self, e: i32) -> Tw {
        debug_assert!(e >= self.e, "twist align must go up");
        let sh = (e - self.e) as u32;
        if sh == 0 {
            return self;
        }
        Tw {
            k1: K7([
                self.k1.0[0] << sh,
                self.k1.0[1] << sh,
                self.k1.0[2] << sh,
            ]),
            k2: K7([
                self.k2.0[0] << sh,
                self.k2.0[1] << sh,
                self.k2.0[2] << sh,
            ]),
            e,
        }
    }

    fn add(self, o: Tw) -> Tw {
        let e = self.e.max(o.e);
        let a = self.align(e);
        let b = o.align(e);
        Tw::new(a.k1.add(b.k1), a.k2.add(b.k2), e)
    }

    fn sub(self, o: Tw) -> Tw {
        let e = self.e.max(o.e);
        let a = self.align(e);
        let b = o.align(e);
        Tw::new(a.k1.sub(b.k1), a.k2.sub(b.k2), e)
    }

    /// Negation (point mirror).
    fn neg(self) -> Tw {
        Tw::new(self.k1.neg(), self.k2.neg(), self.e)
    }

    /// Twist multiplication z·w for z = val(k₁) + i·s·val(k₂) with
    /// s² = (2−b)/4 ∈ K₇: P = k₁l₁ − s²k₂l₂, Q = k₁l₂ + k₂l₁, both at
    /// the scale 2^(e_a+e_b+2) (the ×4 folds in s²' ¼); [`Tw::new`]
    /// normalizes back down.
    fn tmul(self, o: Tw) -> Tw {
        let c1 = self
            .k1
            .mul(o.k1)
            .scale(4)
            .sub(K7([2, -1, 0]).mul(self.k2.mul(o.k2)));
        let c2 = self.k1.mul(o.k2).add(self.k2.mul(o.k1)).scale(4);
        Tw::new(c1, c2, self.e + o.e + 2)
    }

    /// Canonical key for dedup/hash use (the normalized form — the
    /// Python ground truth `tkey`, exactly equivalent).
    fn key(self) -> TKey {
        (self.k1.0, self.k2.0, self.e)
    }

    /// Physical coordinates (emission/geometry floats only).
    fn vec2(self) -> Vec2 {
        let f = (2.0_f64).powi(self.e);
        Vec2::new(self.k1.float() / f, self.k2.float() * S1_F / f)
    }
}

/// Rotation by j·π/7 as a twist multiplier: ζ^j from the certified
/// `ROT14` table (doubled coordinates, exponent 1 before normalization;
/// row 0 normalizes to the identity, row 7 to −1).
fn rot_tw(j: usize) -> Tw {
    let r = &ROT14[j % 14];
    Tw::new(K7([r[0], r[1], r[2]]), K7([r[3], r[4], r[5]]), 1)
}

/// The dihedral action g(j, m, z) = rot_j(mirror_m(z)) — mirror =
/// complex conjugation, (k₁, k₂) → (k₁, −k₂). Python ground truth:
/// `g(j, m, z) = rot(j, tmirror(z)) if m else rot(j, z)` (z first).
fn g_apply(j: usize, m: bool, z: Tw) -> Tw {
    let base = if m { Tw::new(z.k1, z.k2.neg(), z.e) } else { z };
    base.tmul(rot_tw(j))
}

/// Canonical vertex ring of class `cls` (walk order): v₀ = 0, edge
/// directions d_i in π/7 units, v_{i+1} = v_i + ζ^{d_i}, turn
/// d_{i+1} = (d_i + 7 − cyc[i+1]) mod 14. Certified invariants
/// (re-checked as debug asserts): sum(cyc) = 7·(nv−2), the walk closes
/// at the origin with direction 0, and the exact shoelace equals S_T
/// (asserted in the battery).
fn walk_ring(cls: usize) -> Vec<Tw> {
    let nv = NV[cls];
    let cyc = &CYC[cls];
    debug_assert_eq!(cyc.iter().take(nv).sum::<i64>(), 7 * (nv as i64 - 2));
    let mut pts = Vec::with_capacity(nv);
    let mut cur = Tw::new(K7::ZERO, K7::ZERO, 0);
    let mut d: i64 = 0;
    pts.push(cur);
    for i in 0..nv {
        cur = cur.add(rot_tw(d.rem_euclid(14) as usize));
        if i + 1 < nv {
            pts.push(cur);
        }
        d = (d + 7 - cyc[(i + 1) % nv]).rem_euclid(14);
    }
    debug_assert_eq!(d, 0, "ring walk must close with direction 0");
    debug_assert!(cur.is_zero(), "ring walk must close at the origin");
    pts
}

