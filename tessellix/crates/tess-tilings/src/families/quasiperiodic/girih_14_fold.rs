    /// k7_sign fast path (girih_core.py lines 82–96): norm/zero short
    /// cuts, a 2⁻⁵⁰ float envelope, else the exact `K7::sign` bisection.
    fn k7sign(x: K7) -> Ordering {
        if x.is_zero() || x.norm() == 0 {
            return Ordering::Equal;
        }
        let b = K7([0, 1, 0]).float(); // b = 2cos(2π/7) (B_F is crate-private)
        let err = ((x.0[0].abs() as f64)
            + 2.0 * (x.0[1].abs() as f64) * b
            + 3.0 * (x.0[2].abs() as f64) * b * b)
            * (2.0_f64).powi(-50);
        let v1 = x.float();
        if v1.abs() > 3.0 * err {
            if v1 > 0.0 {
                Ordering::Greater
            } else {
                Ordering::Less
            }
        } else {
            x.sign()
        }
    }

    /// sign of cross(b−a, p−a) in the s-scaled plane (s > 0 dropped).
    fn sign_pt(a: Tw, b: Tw, p: Tw) -> Ordering {
        let d1 = b.sub(a);
        let d2 = p.sub(a);
        k7sign(d1.k1.mul(d2.k2).sub(d1.k2.mul(d2.k1)))
    }

    /// sign of the physical dot u·v = val(PuPv) + s²·val(QuQv); the ×4 of
    /// s² = (2−b)/4 is absorbed positively on BOTH terms.
    fn dot_sign(u: Tw, v: Tw) -> Ordering {
        let t1 = u.k1.mul(v.k1).scale(4);
        let t2 = K7([2, -1, 0]).mul(u.k2.mul(v.k2));
        k7sign(t1.add(t2))
    }

    fn on_closed(a: Tw, b: Tw, p: Tw) -> bool {
        if sign_pt(a, b, p) != Ordering::Equal {
            return false;
        }
        dot_sign(p.sub(a), p.sub(b)) != Ordering::Greater
    }

    #[derive(Clone, Copy, Debug, PartialEq, Eq)]
    enum PtLoc {
        On,
        In,
        Out,
    }

    /// Exact crossing-number point-in-polygon with the half-open rule
    /// (girih_core.py `point_vs_polygon`, reflex-safe).
    fn point_vs_polygon(poly: &[Tw], p: Tw) -> PtLoc {
        let n = poly.len();
        for i in 0..n {
            if on_closed(poly[i], poly[(i + 1) % n], p) {
                return PtLoc::On;
            }
        }
        let mut inside = false;
        for i in 0..n {
            let a = poly[i];
            let b = poly[(i + 1) % n];
            let c1 = k7sign(a.sub(p).k2); // sign(Q_a − Q_p); s > 0 irrelevant
            let c2 = k7sign(b.sub(p).k2);
            if (c1 != Ordering::Greater && c2 == Ordering::Greater)
                || (c2 != Ordering::Greater && c1 == Ordering::Greater)
            {
                let pa = p.sub(a);
                let ba = b.sub(a);
                let lhs = pa.k1.mul(ba.k2);
                let rhs = pa.k2.mul(ba.k1);
                let c = k7sign(lhs.sub(rhs));
                if c1 != Ordering::Greater && c2 == Ordering::Greater {
                    if c == Ordering::Less {
                        inside = !inside;
                    }
                } else if c == Ordering::Greater {
                    inside = !inside;
                }
            }
        }
        if inside {
            PtLoc::In
        } else {
            PtLoc::Out
        }
    }

    fn proper_cross(p1: Tw, p2: Tw, q1: Tw, q2: Tw) -> bool {
        let sgn = |o: Ordering| match o {
            Ordering::Less => -1i32,
            Ordering::Equal => 0,
            Ordering::Greater => 1,
        };
        let d1 = sgn(sign_pt(p1, p2, q1));
        let d2 = sgn(sign_pt(p1, p2, q2));
        if d1 * d2 >= 0 {
            return false;
        }
        let d3 = sgn(sign_pt(q1, q2, p1));
        let d4 = sgn(sign_pt(q1, q2, p2));
        d3 * d4 < 0
    }

    fn interiors_disjoint(a: &[Tw], b: &[Tw]) -> bool {
        let na = a.len();
        let nb = b.len();
        for i in 0..na {
            for j in 0..nb {
                if proper_cross(a[i], a[(i + 1) % na], b[j], b[(j + 1) % nb]) {
                    return false;
                }
            }
        }
        point_vs_polygon(b, a[0]) != PtLoc::In && point_vs_polygon(a, b[0]) != PtLoc::In
    }

