        // whole-kid class mix (8 corner G14 + 8 edge D2 + interior).
        let mut panel_mix = [0usize; 11];
        panel_mix[10] += NV[o36];
        panel_mix[7] += NV[o36];
        for e in RULES[o36].iter().skip(NV[o36]) {
            panel_mix[e[0] as usize] += 1;
        }
