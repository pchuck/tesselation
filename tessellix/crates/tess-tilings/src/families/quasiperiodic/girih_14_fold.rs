//! Girih-inspired 14-fold (Pautze) — the Bielefeld entry "Girih 14-fold".
//!
//! Eleven prototiles — the rhombi R2/R3, hexagons H26/H44/H45, octagons
//! O29/O36 (O29 concave), decagons D2/D46/D56 (D2 concave) and the
//! regular 14-gon G14 — with 14-fold point symmetry and inflation
//! **λ = 2b² + 3b** where b = 2cos(2π/7) (minpoly x³ + x² − 2x − 1):
//! λ = (0,3,2) in the b-basis ≈ 6.850855075327, λ² = (8,20,9) ≈
//! 46.93421526313568, **Norm(λ) = −7** — λ is NOT a unit of K₇ (the
//! Bielefeld entry's unit claim is false; see the errata below).
//! [Pau2017] S. Pautze, "Aperiodic tilings with fourteenfold symmetry",
//! *Symmetry* 9(2), 19 (2017), doi:10.3390/sym9020019 (arXiv:1606.06858);
//! Bielefeld Tilings Encyclopedia entry "Girih 14-fold".
//!
//! **Exact arithmetic.** Vertices are points of the module ½Z[ζ₁₄],
//! carried as *twist pairs* (k₁, k₂, e): z = val(k₁) + i·sin(π/7)·val(k₂)
//! scaled by 2⁻e, where val evaluates in K₇ = Q(b) at the real root
//! b ≈ 1.246979603717467 (the [`crate::fields`] isolating-interval
//! machinery). Twist multiplication folds the ¼ of sin²(π/7) = (2−b)/4
//! into a shared exponent ([`Tw::tmul`]); rotations are exact multiplies
//! by ζ^j from the certified `ROT14` table; mirrors conjugate
//! (k₁, k₂) → (k₁, −k₂). Every generated vertex normalizes to dyadic
//! exponent ≤ 1 (re-asserted in tests); f64 appears only at emission and
//! in the standard-coverage windows.
//!
//! **Rule system.** Each class substitutes into a certified panel of
//! whole kids: `nv` corner 14-gons (centered at the parent vertices),
//! `nv` edge decagons (class D2, centered at the exact edge midpoints,
//! mirror-symmetric across the parent edge — half of each lies inside
//! the parent, and adjacent parents emit the *identical* decagon), and
//! the rule-table interior kids. The effective per-class kid matrix N′
//! (interior counts + nv/2 for the shared edge decagons + Σcyc/14 =
//! (nv−2)/2 for the corner 14-gons, each corner 14-gon contributing its
//! k_i/14 wedge) satisfies the exact area law Σ_c N′_rc·S_c = λ²·S_r in
//! K₇ for all 11 rows, and its PF eigenvalue is exactly λ². One full
//! 11-panel round emits 849 kids (19+17+26+45+43+51+66+67+87+105+323).
//!
//! **Generation.** A single centered G14 seed at level N (world scale
//! λᴺ) whose polygon contains the inverse-mapped view bbox (G14 is
//! convex, so the fit tests the four bbox corners only), then per level:
//! substitute all parents (corner → edge → interior, the certified panel
//! order), cull kids whose pad-expanded AABB cannot reach the view, and
//! dedup by exact vertex set (straddling corner rings and edge decagons
//! are bit-identical across incident parents), down to level 0. Coverage
//! is exact panel closure — the polygon interior of every substituted
//! tile is exactly tiled by its certified kids — so the culling pads
//! (derived from the measured kid-vertex excursion δ_v, see
//! [`Tables::pad_unit`]) bound work only, never correctness. Views
//! beyond the area pre-guard (MAX_TILES·sin(2π/7) tile-units²) or the
//! N_MAX = 9 seed cap refuse with a message.
//!
//! **Verification.** The in-module battery re-derives every certified
//! pin: the rule-table rebuild of all 849 rings from the certified brief
//! JSON (`docs/briefs/girih-14-fold-rule.json`, parsed by a hand-rolled
//! in-test parser — the crate has no serde), the exact K₇ area law, the
//! PF eigenvalue, the module + 14-direction census, the two-level R2
//! patch pins (19 → 1813 pre-dedup → 1691 post, zero overlapping-kid
//! pairs by exact predicates), rare-class (O36) coverage, the λ
//! measurement, the per-panel render counts, and the standard trio plus
//! MAX_TILES guards.
//!
//! **Provenance & errata.** The rule tables below are generated from the
//! certified brief JSON and re-verified entry-by-entry against it in
//! tests. (1) The Bielefeld entry's claim that λ is a unit (Norm ±1) is
//! false: Norm(λ) = −7. (2) [Pau2017] Table 7's n = 7 inflation
//! ≈ 5.801939 is contradicted by the paper's own Figs 7.4/7.5 — the
//! measured substitution factor is 6.8507 ± 0.0006 ≈ λ = 6.850855…
//! (certified brief errata; the figures win). (3) The Bielefeld patch
//! specimen is non-generic (O36 absent, deviant PF frequencies on rare
//! classes) and is never used as a census oracle.

