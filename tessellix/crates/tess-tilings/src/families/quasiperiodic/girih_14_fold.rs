    /// Exact shoelace Σ tcross(v_i, v_{i+1}) — equals S (2·area/s) for a
    /// canonical ring (girih_core.py `poly_area_S`).
    fn shoelace_s(verts: &[Tw]) -> Tw {
        let n = verts.len();
        let mut acc = Tw::new(K7::ZERO, K7::ZERO, 0);
        for i in 0..n {
            let a = verts[i];
            let b = verts[(i + 1) % n];
            let e = a.e.max(b.e);
            let (aa, bb) = (a.align(e), b.align(e));
            let c = aa.k1.mul(bb.k2).sub(aa.k2.mul(bb.k1));
            acc = acc.add(Tw::new(c, K7::ZERO, 2 * e));
        }
        acc
    }

    /// Edge direction classes of the canonical ring (girih_core.py
    /// `walk_dirs`): direction d_i (in π/7 units) before the i-th turn.
    fn walk_dirs(cls: usize) -> Vec<i64> {
        let cyc = &CYC[cls];
        let nv = NV[cls];
        let mut d: i64 = 0;
        let mut dirs = Vec::with_capacity(nv);
        for i in 0..nv {
            dirs.push(d);
            d = (d + 7 - cyc[(i + 1) % nv]).rem_euclid(14);
        }
        dirs
    }

    /// All kid rings of class `cls`'s drawing-frame panel (parent at scale
    /// λ, kids at scale 1): nv corner 14-gons, nv edge decagons, then the
    /// rule-table interior kids — the certified `build_panels` order.
    fn panel_rings(t: &Tables, cls: usize) -> Vec<Vec<Tw>> {
        let rt = r_t();
        let mut out = Vec::new();
        for i in 0..NV[cls] {
            let cp = t.lam_pow[1].tmul(t.cv[cls][i]);
            out.push((0..14usize).map(|m| cp.add(rt.tmul(rot_tw(m)))).collect());
        }
        for e in RULES[cls].iter() {
            let tk = Tw::new(K7([e[3], e[4], e[5]]), K7([e[6], e[7], e[8]]), 1);
            let kid = e[0] as usize;
            out.push(
                t.cv[kid]
                    .iter()
                    .map(|w| tk.add(g_apply(e[1] as usize, e[2] != 0, *w)))
                    .collect(),
            );
        }
        out
    }

    fn max_edge(pts: &[Vec2]) -> f64 {
        let n = pts.len();
        let mut best = 0.0_f64;
        for i in 0..n {
            let a = pts[i];
            let b = pts[(i + 1) % n];
            best = best.max(((b.x - a.x).powi(2) + (b.y - a.y).powi(2)).sqrt());
        }
        best
    }

