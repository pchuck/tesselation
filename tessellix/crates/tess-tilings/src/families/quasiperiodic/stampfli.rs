    // ---------- global consistency: refine the star ----------

    /// Substitute every piece once (no culling), deduping straddlers by
    /// exact vertex key — the same semantics as the Python battery.
    fn refine_all(pieces: &[Piece]) -> Vec<Piece> {
        let mut seen: HashSet<Key> = HashSet::with_capacity(pieces.len() * 6);
        let mut out = Vec::with_capacity(pieces.len() * 6);
        for t in pieces {
            for ch in t.children() {
                if seen.insert(ch.key()) {
                    out.push(ch);
                }
            }
        }
        out
    }

    fn counts(pieces: &[Piece]) -> (usize, usize, usize) {
        (
            pieces.iter().filter(|t| t.kind == SQU).count(),
            pieces.iter().filter(|t| t.kind == RHO).count(),
            pieces.iter().filter(|t| t.kind == TRI).count(),
        )
    }

    #[test]
    fn star_growth_counts_follow_orbit() {
        // Verified star-count orbit of the 12-rhombus seed (exact Python
        // Q(√3) growth with exact vertex-set dedup).
        let expect = [
            (24usize, 36usize, 120usize),
            (96, 1116, 1608),
            (2328, 14148, 22104),
        ];
        let mut pieces = seed_star(3);
        for (depth, want) in expect.iter().enumerate() {
            pieces = refine_all(&pieces);
            assert_eq!(counts(&pieces), *want, "depth {depth}");
        }
    }

    #[test]
    fn star_growth_follows_pf_census() {
        // Squares and rhombi never straddle, so their per-generation
        // counts follow the substitution matrix EXACTLY:
        //   S' = 1·S + 2·R        (square + 2 per rhombus)
        //   R' = 12·S + 3·R + 6·T
        // Straddling triangles are shared by two parents in the interior
        // but stand alone on the patch boundary, so the triangle count is
        // AT LEAST the matrix row 16S + 8R + 7T.
        let mut pieces = seed_star(3);
        let (mut s0, mut r0, mut t0) = (0usize, 12usize, 0usize);
        for depth in 0..3u32 {
            pieces = refine_all(&pieces);
            let (s1, r1, t1) = counts(&pieces);
            assert_eq!(s1, s0 + 2 * r0, "depth {depth}: square row");
            assert_eq!(r1, 12 * s0 + 3 * r0 + 6 * t0, "depth {depth}: rhombus row");
            assert!(
                t1 >= 16 * s0 + 8 * r0 + 7 * t0,
                "depth {depth}: triangle row"
            );
            (s0, r0, t0) = (s1, r1, t1);
        }
    }

    #[test]
    fn perron_frobenius_eigenvalue() {
        // The effective substitution matrix (straddlers halved)
        //     M = [[1, 2, 0], [12, 3, 6], [16, 8, 7]]
        // has Perron eigenvalue λ² = 7+4√3 with PF vector
        // v = (1, 3+2√3, 4+10√3/3): tile numbers grow by λ² per inflation.
        let m = [[1.0, 2.0, 0.0], [12.0, 3.0, 6.0], [16.0, 8.0, 7.0]];
        let s3 = SQRT3;
        let v = [1.0, 3.0 + 2.0 * s3, 4.0 + 10.0 * s3 / 3.0];
        let lam2 = 7.0 + 4.0 * s3;
        for i in 0..3 {
            let mv: f64 = (0..3).map(|j| m[i][j] * v[j]).sum();
            assert!(
                (mv - lam2 * v[i]).abs() <= 1e-9 * lam2 * v[i],
                "PF row {i}: {mv} != {}",
                lam2 * v[i]
            );
        }
        // Area weights (1, 1/2, √3/4) are the LEFT eigenvector with the
        // same eigenvalue — equivalently the per-parent PF area law
        // checked by `check_substitution`.
        let w = [1.0, 0.5, s3 / 4.0];
        for j in 0..3 {
            let wm: f64 = (0..3).map(|i| w[i] * m[i][j]).sum();
            assert!(
                (wm - lam2 * w[j]).abs() <= 1e-9 * lam2 * w[j],
                "area row {j}: {wm} != {}",
                lam2 * w[j]
            );
        }
    }

    /// Does point `q` lie strictly in the interior of segment `a-b`?
    fn on_edge_interior(q: Vec2, a: Vec2, b: Vec2) -> bool {
        let ab = b - a;
        let aq = q - a;
        if aq.cross(ab).abs() > 1e-9 {
            return false;
        }
        let s = aq.dot(ab);
        let l2 = ab.dot(ab);
        s > 1e-9 && s < l2 - 1e-9
    }

    #[test]
    fn star_growth_is_edge_to_edge() {
        // The full grown patch (straddlers deduped) is a true tiling:
        // no geometric edge is shared by more than two tiles, and no
        // tile vertex lies in the interior of another tile's edge.
        let mut pieces = seed_star(3);
        for depth in 0..2u32 {
            pieces = refine_all(&pieces);

            // Exact edge census on the Z[√3]/4 integer grid.
            let mut edges: std::collections::BTreeMap<(V4, V4), usize> =
                std::collections::BTreeMap::new();
            for t in &pieces {
                let lp = LAM_POW[t.rem as usize];
                let sq = shape_q(t.kind);
                let n = shape(t.kind).len();
                let ev: Vec<V4> = (0..n)
                    .map(|i| {
                        let (rx, ry) = rot4(sq[i].0, sq[i].1, t.k);
                        let dx = mul_q(rx, lp);
                        let dy = mul_q(ry, lp);
                        (t.mx + dx.0, t.nx + dx.1, t.my + dy.0, t.ny + dy.1)
                    })
                    .collect();
                for i in 0..n {
                    let (a, b) = (ev[i], ev[(i + 1) % n]);
                    let key = if a <= b { (a, b) } else { (b, a) };
                    *edges.entry(key).or_insert(0) += 1;
                }
            }
            for (e, c) in &edges {
                assert!(*c <= 2, "depth {depth}: edge {e:?} shared by {c} tiles");
            }

            // No T-junctions among the (float) tile outlines, bbox-
            // prefilled so the scan stays cheap.
            let polys: Vec<Vec<Vec2>> = pieces.iter().map(|t| t.verts()).collect();
            let boxes: Vec<BBox> = pieces.iter().map(|t| t.aabb()).collect();
            for (i, r) in polys.iter().enumerate() {
                for &v in r {
                    for (j, s) in polys.iter().enumerate() {
                        if i == j || !boxes[j].padding(1e-9).contains_point(v) {
                            continue;
                        }
                        let n = s.len();
                        for k in 0..n {
                            if on_edge_interior(v, s[k], s[(k + 1) % n]) {
                                panic!(
                                    "depth {depth}: T-junction — tile {i} vertex {v} \
                                     lies inside an edge of tile {j}"
                                );
                            }
                        }
                    }
                }
            }
        }
    }

    #[test]
    fn star_growth_is_12fold_symmetric() {
        // The exact deduped vertex-key SET must be invariant under a 30°
        // rotation about the origin. Keys live over 4 (rational, √3)
        // integer pairs; the rotated image lands on the /8 grid, so both
        // sides are expressed there (x' = ((3·bx − yr) + (xr − yb)·√3)/8,
        // y' = ((xr + 3·yb) + (xb + yr)·√3)/8).
        let mut pieces = seed_star(3);
        for _ in 0..2 {
            pieces = refine_all(&pieces);
        }
        type RKey = (u8, [V4; 4]);
        let rkey = |t: &Piece, rotd: bool| -> RKey {
            let lp = LAM_POW[t.rem as usize];
            let sq = shape_q(t.kind);
            let n = shape(t.kind).len();
            // A 30° rotation about the origin maps a /4-grid point
            // (x4a + x4b·√3, y4a + y4b·√3)/4 to the /8 grid:
            //   x' = ((3·x4b − y4a) + (x4a − y4b)·√3)/8
            //   y' = ((x4a + 3·y4b) + (x4b + y4a)·√3)/8
            // Unrotated vertices are expressed on that same /8 grid.
            let a8 = if rotd {
                (
                    3 * t.nx - t.my,
                    t.mx - t.ny,
                    t.mx + 3 * t.ny,
                    t.nx + t.my,
                )
            } else {
                (2 * t.mx, 2 * t.nx, 2 * t.my, 2 * t.ny)
            };
            let kk = t.k + if rotd { 1 } else { 0 };
            let mut out = [(0i64, 0i64, 0i64, 0i64); 4];
            for (i, item) in out.iter_mut().enumerate() {
                let (rx, ry) = rot4(sq[i].0, sq[i].1, kk);
                let dx = mul_q(rx, lp);
                let dy = mul_q(ry, lp);
                // The /8 numerator is `a8 + 2·(4·R_kk(e)·λ^rem)` in both
                // branches — `a8` and `kk` already carry the rotation.
                *item = (a8.0 + 2 * dx.0, a8.1 + 2 * dx.1, a8.2 + 2 * dy.0, a8.3 + 2 * dy.1);
            }
            for slot in out.iter_mut().skip(n) {
                *slot = (i64::MIN, i64::MIN, i64::MIN, i64::MIN);
            }
            out.sort_unstable();
            (t.kind, out)
        };
        let mut set: std::collections::BTreeSet<RKey> = std::collections::BTreeSet::new();
        for t in &pieces {
            set.insert(rkey(t, false));
        }
        for t in &pieces {
            let r = rkey(t, true);
            assert!(set.contains(&r), "12-fold symmetry mismatch at {:?}", r);
        }
    }
