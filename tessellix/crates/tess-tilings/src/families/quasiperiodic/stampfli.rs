//! Stampfli's 12-fold (dodecagonal) quasiperiodic tiling by substitution.
//!
//! Prototiles: the unit square, the equilateral triangle, and the 30°
//! rhombus — the three tiles that meet around every vertex of Stampfli's
//! classic construction, whose inflation factor is `λ = 2+√3` (every
//! vertex of every child lies in `Z[√3]/4` scaled by the child size, so
//! all coordinates are `m + n·√3` with rational `m, n`).
//!
//! Substitution counts (effective, i.e. boundary-straddling triangles
//! halved; PF matrix `[[1,2,0],[12,3,6],[16,8,7]]`, Perron eigenvalue
//! `λ² = 7+4√3`, PF vector `(1, 3+2√3, 4+⅓·10·√3)`):
//!
//! ```text
//! triangle ->  6 rhombi + 10 triangles (+ 6 half-outside straddlers)
//! rhombus  ->  2 squares + 3 rhombi + 12 triangles (+ 8 straddlers)
//! square   ->  1 square + 12 rhombi + 20 triangles (+ 8 straddlers)
//! ```
//!
//! The straddlers are the heart of the rule: a child patch is substituted
//! in the λ-inflated parent frame, and a few unit triangles per parent
//! straddle the parent's boundary — base ON the edge, apex sticking out at
//! the mirror-image position. Every interior parent edge carries the SAME
//! mirror-symmetric partition `[1, √3/2, √3/2, 1]` (two half-outside
//! triangle bases meeting base-to-base at the edge midpoint), which is
//! exactly what makes growth across parent boundaries consistent and
//! edge-to-edge; globally, each straddling triangle is generated by its
//! two adjacent parents with identical geometry, so pieces are deduped by
//! their exact integer vertex set (the analogue of the Ammann–Beenker
//! hypotenuse pairing, and the reason a `(kind, orientation, anchor)`
//! key would NOT suffice — the same tile can appear in different
//! orientation/anchor representations).
//!
//! Canonical pieces (unit edge; orientation `k` rotates by `30°·k` CCW):
//!
//! * triangle: `(0,0), (1,0), (1/2, √3/2)`
//! * rhombus:  `(0,0), (1,0), (1+√3/2, 1/2), (√3/2, 1/2)`
//! * square:   `(0,0), (1,0), (1,1), (0,1)`
//!
//! Child tables below are transcribed verbatim from the canonical rule
//! figure of the Tilings Encyclopedia entry "Stampfli's 12-fold 1"
//! (groups `Dreieck-R01`, `Raute-R01`, `Quadrat-R01`), which draws the
//! substitution at scale 1/(2+√3) around each parent. Each child anchor
//! is given in the λ-inflated parent frame (child-edge units) as
//! `((ox1 + ox2·√3)/2, (oy1 + oy2·√3)/2)` plus an orientation delta in
//! 30° steps. Anchors accumulate EXACTLY: a piece carries its position
//! as `(mx + nx·√3)/4` integer pairs, and the child update adds
//! `4·R_k(anchor)·λ^(rem−1)` with `λ^i ∈ Z[√3]` — no floating-point
//! drift, so the straddler dedup key is exact at every depth.
//!
//! Verification history (exact `Q(√3)` arithmetic, Python, before this
//! implementation): each rule's children cover its inflated parent
//! exactly once (half-weighted straddler areas give the PF area law
//! `n_S + n_R/2 + (√3/4)·n_T = λ²·|parent|` per parent); the edge
//! partition above holds on every edge of every parent; growing the
//! 12-rhombus star to depth 4 stays edge-to-edge (zero T-junctions, no
//! edge covered more than twice, zero pairwise overlaps) and exactly
//! 12-fold symmetric; the star count orbit is
//! (24 S, 36 R, 120 T), (96, 1116, 1608), (2328, 14148, 22104),
//! (30624, 203004, 306696). The Rust tests re-check the per-parent
//! covers, the count orbit, the census rows, edge-to-edge growth and the
//! 12-fold symmetry of the star patches.
//!
//! Growth mirrors the Ammann–Beenker module: seed with the 12-rhombus
//! star scaled to cover the view (its inscribed radius is `1/2·scale`),
//! then repeatedly deflate. A child may stick out of its parent by at
//! most `√3/2·s_child`, and a piece's whole descendant cone reaches at
//! most `√3/2·s/(λ−1) < 0.32·s` outside it, so per-step culling keeps
//! every piece whose aabb meets the region grown by `0.5·s` — nothing
//! that covers the region is ever dropped.

