    /// Parent one inflation level above a canonical unit piece, so its
    /// substitution children are unit pieces exactly as in the verified
    /// Python tables.
    fn canonical_parent(kind: u8) -> Piece {
        Piece {
            kind,
            k: 0,
            mx: 0,
            nx: 0,
            my: 0,
            ny: 0,
            rem: 1,
        }
    }

    /// Deterministic xorshift64 rng (same style as the lib tests).
    struct Rng(u64);
    impl Rng {
        fn f64(&mut self) -> f64 {
            let mut v = self.0;
            v ^= v << 13;
            v ^= v >> 7;
            v ^= v << 17;
            self.0 = v;
            (v >> 11) as f64 * (1.0 / 9007199254740992.0)
        }
    }

    /// Point in convex polygon (boundary counts as inside).
    fn poly_contains(vs: &[Vec2], q: Vec2) -> bool {
        let n = vs.len();
        let mut pos = false;
        let mut neg = false;
        for i in 0..n {
            let c = (vs[(i + 1) % n] - vs[i]).cross(q - vs[i]);
            if c > 1e-9 {
                pos = true;
            } else if c < -1e-9 {
                neg = true;
            }
        }
        !(pos && neg)
    }

    /// Each rule: children cover the inflated parent exactly once, only
    /// triangles straddle (with exactly one vertex outside, base on the
    /// parent edge, hence half inside), and the half-weighted child areas
    /// obey the PF area law `n_S + n_R/2 + (√3/4)·n_T = λ²·|parent|`.
    fn check_substitution(kind: u8, want: (usize, usize, usize), straddlers: usize, label: &str) {
        let parent = canonical_parent(kind);
        let kids = parent.children();
        assert_eq!(kids.len(), want.0 + want.1 + want.2, "{label}: child count");
        let pv = parent.verts();

        let mut ns = 0;
        let mut nr = 0;
        let mut nt = 0;
        let mut straddle = 0;
        let mut law = 0.0_f64;
        for kid in &kids {
            match kid.kind {
                SQU => ns += 1,
                RHO => nr += 1,
                _ => nt += 1,
            }
            let kv = kid.verts();
            let outside: Vec<usize> = kv
                .iter()
                .enumerate()
                .filter(|(_, &q)| !poly_contains(&pv, q))
                .map(|(i, _)| i)
                .collect();
            let area = kid.poly().area();
            if outside.is_empty() {
                law += area;
            } else {
                // Straddlers are triangles with exactly ONE vertex outside.
                assert_eq!(kid.kind, TRI, "{label}: straddler is not a triangle");
                assert_eq!(
                    outside.len(),
                    1,
                    "{label}: straddler has {} vertices outside",
                    outside.len()
                );
                straddle += 1;
                // base on the parent edge => exactly half inside
                law += 0.5 * area;
            }
        }
        assert_eq!((ns, nr, nt), want, "{label}: child kind counts");
        assert_eq!(straddle, straddlers, "{label}: straddler count");

        let pa = parent.poly().area();
        // The parent has edge λ, so its area is λ²·(unit area) — exactly
        // what the half-weighted unit children must sum to.
        let want_law = pa;
        assert!(
            (law - want_law).abs() <= 1e-9 * want_law,
            "{label}: half-weighted child area {law} != λ²·parent {want_law}"
        );

        // Every interior sample point of the parent lies in exactly one
        // child (coverage without overlap).
        let bb = parent.aabb();
        let mut rng = Rng(0x517C_C1B7_2722_0A95);
        let mut checked = 0;
        for _ in 0..4000 {
            let q = Vec2::new(
                bb.min.x + rng.f64() * bb.size().x,
                bb.min.y + rng.f64() * bb.size().y,
            );
            if !poly_contains(&pv, q) {
                continue;
            }
            let n = kids
                .iter()
                .filter(|k| poly_contains(&k.verts(), q))
                .count();
            assert!(n == 1, "{label}: point {q} covered by {n} children");
            checked += 1;
        }
        assert!(checked > 1000, "{label}: too few samples landed");
    }

