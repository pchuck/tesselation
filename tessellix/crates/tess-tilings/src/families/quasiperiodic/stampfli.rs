/// `λ^i` as `(rational, √3)` integer pairs, `i = 0..=STEP_CAP`.
const fn lam_pows() -> [(i64, i64); STEP_CAP + 1] {
    let mut out = [(0i64, 0i64); STEP_CAP + 1];
    out[0] = (1, 0);
    let mut i = 1;
    while i <= STEP_CAP {
        let (a, b) = out[i - 1];
        // (a + b√3)(2 + √3) = (2a + 3b) + (a + 2b)√3
        out[i] = (2 * a + 3 * b, a + 2 * b);
        i += 1;
    }
    out
}
static LAM_POW: [(i64, i64); STEP_CAP + 1] = lam_pows();

/// Rotation by `k·30°` as `(c1, c2, s1, s2)` with `c = (c1 + c2·√3)/2`,
/// `s = (s1 + s2·√3)/2` (cos and sin of `k·30°`).
const ROT: [[i64; 4]; 12] = [
    [2, 0, 0, 0],
    [0, 1, 1, 0],
    [1, 0, 0, 1],
    [0, 0, 2, 0],
    [-1, 0, 0, 1],
    [0, -1, 1, 0],
    [-2, 0, 0, 0],
    [0, -1, -1, 0],
    [-1, 0, 0, -1],
    [0, 0, -2, 0],
    [1, 0, 0, -1],
    [0, 1, -1, 0],
];

/// `(a + b√3)(c + d√3)` exactly.
fn mul_q(p: (i64, i64), q: (i64, i64)) -> (i64, i64) {
    (
        p.0 * q.0 + 3 * p.1 * q.1,
        p.0 * q.1 + p.1 * q.0,
    )
}

/// `4·R_k(v)` where `v` is the vector `((x.0 + x.1·√3)/2, (y.0 + y.1·√3)/2)`,
/// returned as `(x', y')` integer pairs over 4.
fn rot4(x: (i64, i64), y: (i64, i64), k: i32) -> ((i64, i64), (i64, i64)) {
    let r = &ROT[k.rem_euclid(12) as usize];
    let (c1, c2, s1, s2) = (r[0], r[1], r[2], r[3]);
    (
        (
            c1 * x.0 + 3 * c2 * x.1 - s1 * y.0 - 3 * s2 * y.1,
            c1 * x.1 + c2 * x.0 - s1 * y.1 - s2 * y.0,
        ),
        (
            s1 * x.0 + 3 * s2 * x.1 + c1 * y.0 + 3 * c2 * y.1,
            s1 * x.1 + s2 * x.0 + c1 * y.1 + c2 * y.0,
        ),
    )
}

/// Rotate a float vector by `k` 30° CCW steps.
fn rot30(v: Vec2) -> Vec2 {
    Vec2::new(H3 * v.x - 0.5 * v.y, 0.5 * v.x + H3 * v.y)
}

fn rot(v: Vec2, k: i32) -> Vec2 {
    let mut v = v;
    for _ in 0..k.rem_euclid(12) {
        v = rot30(v);
    }
    v
}

/// A piece: prototile `kind`, orientation `k` (30° CCW steps), exact
/// anchor `((mx + nx·√3)/4, (my + ny·√3)/4)` in tile units, and `rem`
/// remaining subdivision steps — its edge length is `λ^rem` tile units.
#[derive(Clone, Copy, Debug)]
struct Piece {
    kind: u8,
    k: i32,
    mx: i64,
    nx: i64,
    my: i64,
    ny: i64,
    rem: u8,
}

/// Exact vertex-set key: `(kind, sorted 4-vertices)` where each vertex is
/// `(x_rational, x_sqrt3, y_rational, y_sqrt3)` over 4. Identical tiles
/// reached through different parent paths share this key bit-for-bit,
/// regardless of which `(k, anchor)` representation a rule emitted.
type Key = (u8, [V4; 4]);

impl Piece {
    fn anchor(&self) -> Vec2 {
        Vec2::new(
            (self.mx as f64 + self.nx as f64 * SQRT3) * 0.25,
            (self.my as f64 + self.ny as f64 * SQRT3) * 0.25,
        )
    }

    fn scale(&self) -> f64 {
        LAMF[self.rem as usize]
    }

    fn verts(&self) -> Vec<Vec2> {
        let a = self.anchor();
        let s = self.scale();
        shape(self.kind)
            .iter()
            .map(|&c| a + rot(c, self.k) * s)
            .collect()
    }

    fn poly(&self) -> Polygon {
        Polygon::from_slice(&self.verts())
    }

    fn aabb(&self) -> BBox {
        let a = self.anchor();
        let s = self.scale();
        let mut lo = Vec2::new(f64::MAX, f64::MAX);
        let mut hi = Vec2::new(f64::MIN, f64::MIN);
        for &c in shape(self.kind) {
            let q = a + rot(c, self.k) * s;
            lo.x = lo.x.min(q.x);
            lo.y = lo.y.min(q.y);
            hi.x = hi.x.max(q.x);
            hi.y = hi.y.max(q.y);
        }
        BBox::new(lo, hi)
    }

    fn key(&self) -> Key {
        let lp = LAM_POW[self.rem as usize];
        let sq = shape_q(self.kind);
        let n = shape(self.kind).len();
        let mut v = [(0i64, 0i64, 0i64, 0i64); 4];
        for (i, item) in v.iter_mut().enumerate() {
            let (rx, ry) = rot4(sq[i].0, sq[i].1, self.k);
            let dx = mul_q(rx, lp);
            let dy = mul_q(ry, lp);
            *item = (
                self.mx + dx.0,
                self.nx + dx.1,
                self.my + dy.0,
                self.ny + dy.1,
            );
        }
        // PAD unused triangle slots to the MIN sentinel: `kind` is part of
        // the key, so padding can never collide with a real rhombus/square
        // vertex — and sorting keeps the key representation-order-free.
        if n < 4 {
            v[n] = (i64::MIN, i64::MIN, i64::MIN, i64::MIN);
        }
        v.sort_unstable();
        (self.kind, v)
    }

    /// Substitution children. With `rem = r > 0` the parent has edge
    /// `λ^r`; children have edge `λ^(r-1)` and anchors at
    /// `parent + R_k(offset)·λ^(r-1)` — all exact in `Z[√3]`.
    fn children(&self) -> Vec<Piece> {
        let rem = self.rem - 1;
        let lp = LAM_POW[rem as usize];
        rule(self.kind)
            .iter()
            .map(|&(kind, dk, ox1, ox2, oy1, oy2)| {
                let (rx, ry) = rot4((ox1, ox2), (oy1, oy2), self.k);
                let dx = mul_q(rx, lp);
                let dy = mul_q(ry, lp);
                Piece {
                    kind,
                    k: self.k + dk,
                    mx: self.mx + dx.0,
                    nx: self.nx + dx.1,
                    my: self.my + dy.0,
                    ny: self.ny + dy.1,
                    rem,
                }
            })
            .collect()
    }
}

static LAMF: [f64; STEP_CAP + 1] = {
    let mut out = [0.0; STEP_CAP + 1];
    out[0] = 1.0;
    let mut i = 1;
    while i <= STEP_CAP {
        out[i] = out[i - 1] * LAM;
        i += 1;
    }
    out
};

/// The "star" seed: 12 rhombi meeting at the origin — Stampfli's classic
/// dodecagonal rosette core with perfect 12-fold symmetry. Its outer
/// boundary is a 24-gon of inradius `1/2·scale`.
fn seed_star(rem: u8) -> Vec<Piece> {
    (0..12)
        .map(|k| Piece {
            kind: RHO,
            k,
            mx: 0,
            nx: 0,
            my: 0,
            ny: 0,
            rem,
        })
        .collect()
}

/// One deflation step: replace every piece by its substitution children
/// (scale `1/λ`), deduping the straddling triangles by exact vertex key.
///
/// Culling: a piece's entire descendant cone reaches at most
/// `√3/2 · s / (λ−1) < 0.32·s` beyond it, so keeping every child whose
/// aabb meets the region grown by `0.5·s_child` never drops a tile that
/// would cover the region.
fn refine_step(pieces: &[Piece], region: &BBox) -> Vec<Piece> {
    let mut out = Vec::with_capacity(pieces.len() * 6);
    let mut seen: HashSet<Key> = HashSet::with_capacity(pieces.len() * 6);
    for t in pieces {
        let pad = 0.5 * LAMF[(t.rem - 1) as usize];
        let rpad = BBox::new(region.min - Vec2::new(pad, pad), region.max + Vec2::new(pad, pad));
        for ch in t.children() {
            if ch.aabb().intersects(rpad) && seen.insert(ch.key()) {
                out.push(ch);
            }
        }
    }
    out
}

/// Stampfli 12-fold tiling (aperiodic, squares + triangles + 30° rhombi,
/// local 12-fold symmetry).
pub struct StampfliTiling;

impl Tiling for StampfliTiling {
    fn id(&self) -> &'static str {
        "stampfli"
    }

    fn name(&self) -> &'static str {
        "Stampfli (12-fold)"
    }

    fn description(&self) -> &'static str {
        "Quasiperiodic square-triangle-rhombus tiling by substitution; local 12-fold symmetry, inflation 2+sqrt(3)."
    }

    fn category(&self) -> TilingCategory {
        TilingCategory::Quasiperiodic
    }

    fn params(&self) -> &'static [ParamSpec] {
        &SIMILARITY_PARAMS
    }

    fn default_color_mode(&self) -> ColorMode {
        ColorMode::Pattern
    }

    fn generate(&self, params: &ParamSet, query: &Query) -> TilingResult {
        let meta = SymmetryMeta::new(WallpaperGroup::P1, LatticeKind::None)
            .with_notes("aperiodic; local 12-fold symmetry");
        let fail = |message: &'static str| TilingResult {
            tiles: Vec::new(),
            symmetry: meta,
            periodic: None,
            message: Some(message),
        };

        let map = similarity_map(params);
        let inv = map.inverse();

        // Region in the tiling's own (cell) coordinates: the axis-aligned
        // box around the inverse image of the four world corners.
        let mut rmin = Vec2::new(f64::MAX, f64::MAX);
        let mut rmax = Vec2::new(f64::MIN, f64::MIN);
        for &corner in &query.region.corners() {
            let q = inv.transform(corner);
            rmin.x = rmin.x.min(q.x);
            rmin.y = rmin.y.min(q.y);
            rmax.x = rmax.x.max(q.x);
            rmax.y = rmax.y.max(q.y);
        }
        let region = BBox::new(rmin, rmax);

        // Farthest region corner from the origin (the seed star is
        // centered there).
        let mut reach: f64 = 0.0;
        for &corner in &region.corners() {
            reach = reach.max(corner.length());
        }
        if reach < 1e-9 {
            return fail("empty view");
        }

        // Pre-generation budget (mirrors lattice.rs): the returned tiles
        // must cover the query region and no Stampfli tile exceeds the
        // unit square's area (cell units; pieces only get smaller than
        // unit scale), so this is a lower bound on the tile count.
        let s = params.float(SCALE_ID, 1.0);
        if query.region.area() / (s * s) > MAX_TILES as f64 {
            return fail("too many tiles for this view — zoom in");
        }

        // Seed scale: the star's inscribed radius is 1/2·scale, so pick
        // scale = λ^n with n minimal subject to 2·reach ≤ scale; the
        // refinement below then lands exactly on unit pieces.
        let mut scale = 1.0_f64;
        let mut steps = 0_usize;
        while 2.0 * reach > scale && steps < STEP_CAP {
            scale *= LAM;
            steps += 1;
        }
        if 2.0 * reach > scale * (1.0 + 1e-9) {
            return fail("view too far from the seed — pan back or zoom in");
        }

        let mut pieces = seed_star(steps as u8);
        for _ in 0..steps {
            pieces = refine_step(&pieces, &region);
        }
        if pieces.is_empty() {
            return fail("empty view");
        }

        let mut tiles = Vec::new();
        for t in &pieces {
            let world = t.poly().transform(&map);
            if world.aabb().intersects(query.region) {
                tiles.push(Tile { family: tess_core::tiling::FamilyTag::None, reflected: false,
                    proto: t.kind,
                    seed: t.kind as u32, level: steps as u8,
                    poly: world,
                });
            }
        }

        if tiles.len() > MAX_TILES {
            return fail("too many tiles for this view — zoom in");
        }

        TilingResult {
            tiles,
            symmetry: meta,
            periodic: None,
            message: None,
        }
    }
}

#[cfg(test)]
