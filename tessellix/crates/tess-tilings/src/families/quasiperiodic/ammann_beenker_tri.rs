    // ---------- global consistency: refine the star ----------

    /// Substitute every piece once (no culling).
    fn refine_all(pieces: &[Piece]) -> Vec<Piece> {
        let mut out = Vec::with_capacity(pieces.len() * 5);
        for t in pieces {
            out.extend(t.children());
        }
        out
    }

    #[test]
    fn star_growth_counts_follow_substitution_matrix() {
        // rhombus -> 3r + 2R + 2L ; R-triangle -> 2r + 2R + 1L ;
        // L-triangle -> 2r + 1R + 2L. From the 8-rhombus star this
        // gives the PF-orbit (24, 16, 16), (136, 96, 96), (792, 560, 560).
        let mut pieces = seed_star(1.0);
        let (mut er, mut eq, mut el) = (8usize, 0usize, 0usize);
        for depth in 0..3u32 {
            pieces = refine_all(&pieces);
            let (r, q, l) = (
                3 * er + 2 * eq + 2 * el,
                2 * er + 2 * eq + el,
                2 * er + eq + 2 * el,
            );
            er = r;
            eq = q;
            el = l;
            let gr = pieces.iter().filter(|t| t.kind == RHOMB).count();
            let gq = pieces.iter().filter(|t| t.kind == RSQ).count();
            let gl = pieces.iter().filter(|t| t.kind == LSQ).count();
            assert_eq!(
                (gr, gq, gl),
                (er, eq, el),
                "depth {depth}: got ({gr}, {gq}, {gl}), want ({er}, {eq}, {el})"
            );
        }
    }

    /// Does point `q` lie strictly in the interior of segment `a-b`?
    fn on_edge_interior(q: Vec2, a: Vec2, b: Vec2) -> bool {
        let ab = b - a;
        let aq = q - a;
        if aq.cross(ab).abs() > 1e-9 {
            return false;
        }
        let s = aq.dot(ab);
        let l2 = ab.dot(ab);
        s > 1e-9 && s < l2 - 1e-9
    }

    /// Key of the unordered segment `(a, b)` on the 1e-7 grid (the same
    /// convention as the classic entry's hypotenuse pairing; Z[√2]
    /// lattice points reached through different substitution paths agree
    /// to far below half a grid step at the scales STEP_CAP allows).
    fn seg_key(a: Vec2, b: Vec2) -> (i64, i64, i64, i64) {
        let (ax, ay) = ((a.x * 1e7).round() as i64, (a.y * 1e7).round() as i64);
        let (bx, by) = ((b.x * 1e7).round() as i64, (b.y * 1e7).round() as i64);
        if (ax, ay) <= (bx, by) {
            (ax, ay, bx, by)
        } else {
            (bx, by, ax, ay)
        }
    }

    /// Hypotenuse groups of the triangle pieces: every shared hypotenuse
    /// pairs one R and one L triangle, at most two halves per segment.
    fn hyp_groups(pieces: &[Piece]) -> BTreeMap<(i64, i64, i64, i64), Vec<usize>> {
        let mut groups: BTreeMap<(i64, i64, i64, i64), Vec<usize>> = BTreeMap::new();
        for (i, t) in pieces.iter().enumerate() {
            if t.kind == RHOMB {
                continue;
            }
            let b = t.p + rot(Vec2::new(1.0, 1.0), t.k) * t.s;
            groups.entry(seg_key(t.p, b)).or_default().push(i);
        }
        groups
    }

    #[test]
    fn star_growth_is_edge_to_edge() {
        // Unlike the classic entry, every piece is its own tile — rhombi
        // as 4-gons, every half-square as a triangle — so the patch must
        // be edge-to-edge across all pieces (no T-junctions anywhere).
        let star_area = 8.0 * S2;
        let mut pieces = seed_star(1.0);
        for depth in 0..3u32 {
            pieces = refine_all(&pieces);

            let area: f64 = pieces.iter().map(|t| t.poly().area()).sum();
            assert!(
                (area - star_area).abs() <= 1e-9 * star_area,
                "depth {depth}: piece area sum {area} != star area {star_area}"
            );

            for idxs in hyp_groups(&pieces).values() {
                assert!(
                    idxs.len() <= 2,
                    "depth {depth}: hypotenuse shared by {} halves",
                    idxs.len()
                );
                if idxs.len() == 2 {
                    let (a, b) = (pieces[idxs[0]], pieces[idxs[1]]);
                    assert_ne!(
                        a.kind, b.kind,
                        "depth {depth}: hypotenuse pairs same-label halves"
                    );
                }
            }

            let polys: Vec<Vec<Vec2>> = pieces.iter().map(|t| t.verts()).collect();
            for i in 0..polys.len() {
                for &v in &polys[i] {
                    for (j, s) in polys.iter().enumerate() {
                        if i == j {
                            continue;
                        }
                        let n = s.len();
                        for k in 0..n {
                            if on_edge_interior(v, s[k], s[(k + 1) % n]) {
                                panic!(
                                    "depth {depth}: T-junction — tile {i} vertex {v} \
                                     lies inside an edge of tile {j}"
                                );
                            }
                        }
                    }
                }
            }
        }
    }

    #[test]
    fn star_growth_parity_matches_standard_pairing() {
        // H = 2P + U with P paired R-L hypotenuse pairs (the squares the
        // classic entry emits) and U unpaired boundary halves. The
        // classic square-emitting patch (P squares of area 1 + U boundary
        // triangles of area ½ at scale s) therefore has the same total
        // area as this one: (r·√2/2 + P + U/2)·s² = 8·√2/2, the fixed
        // area of the star, at every depth.
        let star_area = 8.0 * S2;
        let mut pieces = seed_star(1.0);
        let mut s = 1.0_f64;
        for depth in 0..4u32 {
            pieces = refine_all(&pieces);
            s /= LAM;

            let mut p = 0usize;
            let mut u = 0usize;
            for idxs in hyp_groups(&pieces).values() {
                match idxs.len() {
                    2 => {
                        p += 1;
                        let (a, b) = (pieces[idxs[0]], pieces[idxs[1]]);
                        assert_ne!(
                            a.kind, b.kind,
                            "depth {depth}: hypotenuse pairs same-label halves"
                        );
                    }
                    1 => u += 1,
                    n => panic!("depth {depth}: hypotenuse shared by {n} halves"),
                }
            }
            let h = pieces.iter().filter(|t| t.kind != RHOMB).count();
            assert_eq!(h, 2 * p + u, "depth {depth}: H = {h} != 2P + U = {}", 2 * p + u);

            let r = pieces.iter().filter(|t| t.kind == RHOMB).count() as f64;
            let classic_area = (r * S2 + p as f64 + u as f64 / 2.0) * s * s;
            assert!(
                (classic_area - star_area).abs() <= 1e-9 * star_area,
                "depth {depth}: area parity {classic_area} != star area {star_area}"
            );
        }
    }

    #[test]
    fn star_growth_is_8fold_symmetric() {
        // The labelled piece multiset must be invariant under a 45°
        // rotation about the origin: (kind, k, p) -> (kind, k+1, rot45 p).
        let mut pieces = seed_star(1.0);
        for _ in 0..2 {
            pieces = refine_all(&pieces);
        }
        type Key = (u8, i32, i64, i64);
        let key = |t: &Piece, r: bool| -> Key {
            let p = if r { rot45(t.p) } else { t.p };
            (
                t.kind,
                if r { t.k + 1 } else { t.k }.rem_euclid(8),
                (p.x * 1e4).round() as i64,
                (p.y * 1e4).round() as i64,
            )
        };
        let mut count: BTreeMap<Key, i32> = BTreeMap::new();
        for t in &pieces {
            *count.entry(key(t, false)).or_insert(0) += 1;
        }
        for t in &pieces {
            *count.entry(key(t, true)).or_insert(0) -= 1;
        }
        for (k, &n) in &count {
            assert_eq!(n, 0, "8-fold symmetry mismatch at {k:?}");
        }
    }
