    /// The handoff battery, re-derived in Rust on the shipped tables:
    /// exactly the study's JSON numbers, H 0/9900 and V 0/9900 edge
    /// mismatches, compared on the exact 9-colour ids (before the
    /// magenta/pink palette merge).
    #[test]
    fn jr_handoff_battery() {
        // The palette-id table and the exact-colour table agree
        // throughout (the merge is exactly the documented one).
        for (t, &(n, e, s, w)) in TILES.iter().enumerate() {
            for (slot, &pal) in [n, e, s, w].iter().enumerate() {
                assert_eq!(
                    pal,
                    PALETTE_OF[usize::from(TILE_COLORS[t * 4 + slot])],
                    "tile {t} slot {slot}: palette id disagrees with exact colour"
                );
            }
        }
        // The 9 distinct colours are indexed densely from 0, one
        // COLOR_NAMES entry per id (the human-readable legend).
        assert_eq!(
            usize::from(*TILE_COLORS.iter().max().unwrap()) + 1,
            COLOR_NAMES.len(),
            "colour ids dense over COLOR_NAMES"
        );
        let (mut h_edges, mut h_bad, mut v_edges, mut v_bad) = (0usize, 0usize, 0usize, 0usize);
        for y in 0..SIZE {
            for x in 0..SIZE {
                let l = usize::from(PATCH[y * SIZE + x]);
                if x + 1 < SIZE {
                    h_edges += 1;
                    let r = usize::from(PATCH[y * SIZE + x + 1]);
                    if TILE_COLORS[l * 4 + 1] != TILE_COLORS[r * 4 + 3] {
                        h_bad += 1;
                    }
                }
                if y + 1 < SIZE {
                    v_edges += 1;
                    let d = usize::from(PATCH[(y + 1) * SIZE + x]);
                    if TILE_COLORS[l * 4 + 2] != TILE_COLORS[d * 4] {
                        v_bad += 1;
                    }
                }
            }
        }
        assert_eq!(
            (h_edges, h_bad),
            (9900, 0),
            "H battery (edges, mismatches)"
        );
        assert_eq!(
            (v_edges, v_bad),
            (9900, 0),
            "V battery (edges, mismatches)"
        );
    }

    /// Tile frequencies over the shipped patch, vs the handoff's table.
    #[test]
    fn jr_tile_frequencies() {
        let mut f = [0u16; 11];
        for &t in PATCH.iter() {
            f[usize::from(t)] += 1;
        }
        assert_eq!(f, FREQ, "frequency table");
        assert_eq!(f.iter().sum::<u16>(), 10000, "patch has 10000 cells");
    }

    /// No grid translation period |t| <= 30 of the shipped patch: of the
    /// 2820 nonzero translations with dx^2 + dy^2 <= 900, none preserves
    /// the tile assignment over an overlap of >= 3 cells (mirrors the
    /// study's battery.translation_periods_100x100_le30 == []).
    #[test]
    fn jr_has_no_period_to_radius_30() {
        let mut tested = 0usize;
        for dx in -30i16..=30 {
            for dy in -30i16..=30 {
                if dx == 0 && dy == 0 {
                    continue;
                }
                if dx * dx + dy * dy > 900 {
                    continue;
                }
                tested += 1;
                let y0 = 0.max(dy) as usize;
                let y1 = 100.min(100 + dy) as usize;
                let x0 = 0.max(dx) as usize;
                let x1 = 100.min(100 + dx) as usize;
                let (mut ov, mut mt) = (0usize, 0usize);
                for y2 in y0..y1 {
                    let ry = (y2 as i16 - dy) as usize;
                    for x2 in x0..x1 {
                        let rx = (x2 as i16 - dx) as usize;
                        ov += 1;
                        if PATCH[y2 * SIZE + x2] == PATCH[ry * SIZE + rx] {
                            mt += 1;
                        }
                    }
                }
                assert!(
                    ov < 3 || mt != ov,
                    "translation ({dx},{dy}) is a period: {mt}/{ov} cells match"
                );
            }
        }
        assert_eq!(tested, PROBES, "translations probed");
    }

    /// Partition mandate, measured on emitted tiles: a query over the
    /// whole patch returns exactly 10000 * 4 triangles, every cell's
    /// four triangle areas sum to 1, and the emission is fully
    /// accounted for. ×4 (4 triangles per cell, up from 5 sub-polygons
    /// in the band scheme); the area-sum is 1 per cell in both schemes.
    #[test]
    fn jr_partition_areas_sum_to_cell() {
        fn signature(proto: u8, seed: u32, pts: &[Vec2]) -> String {
            let mut key = format!("{proto}:{seed}");
            for q in pts {
                key.push_str(&format!(",{:.6}", q.x));
                key.push_str(&format!(",{:.6}", q.y));
            }
            key
        }
        let p = ParamSet::default_for(JeandelRaoTiling.params());
        let r = JeandelRaoTiling.generate(
            &p,
            &Query {
                region: BBox::new(Vec2::new(-50.0, -50.0), Vec2::new(50.0, 50.0)),
            },
        );
        assert!(r.message.is_none(), "{:?}", r.message);
        assert_eq!(r.tiles.len(), SIZE * SIZE * 4, "whole-patch triangle count");
        let mut pool: HashMap<String, usize> = HashMap::new();
        for t in &r.tiles {
            *pool.entry(signature(t.proto, t.seed, &t.poly.pts)).or_insert(0) += 1;
        }
        let triangles = local_triangles();
        for y in 0..SIZE {
            for x in 0..SIZE {
                let t = usize::from(PATCH[y * SIZE + x]);
                let (n, e, s, w) = TILES[t];
                let seeds = [n, e, s, w];
                let c = cell_centre(x, y);
                let mut sum = 0.0;
                for (i, (proto, off)) in triangles.iter().enumerate() {
                    let pts: Vec<Vec2> = (0..3)
                        .map(|k| Vec2::new(c.x + off[2 * k], c.y + off[2 * k + 1]))
                        .collect();
                    let hit = pool.get_mut(&signature(
                        *proto,
                        u32::from(seeds[i]),
                        &pts,
                    ));
                    assert!(
                        hit.is_some_and(|n2| {
                            *n2 -= 1;
                            *n2 < usize::MAX
                        }),
                        "cell ({x},{y}) piece {i} missing from the emission"
                    );
                    sum += Polygon::from_slice(&pts).area();
                }
                assert!(
                    (sum - 1.0).abs() < 1e-9,
                    "cell ({x},{y}): 4 triangle areas sum to {sum}, want 1"
                );
            }
        }
        assert!(
            pool.values().all(|n| *n == 0),
            "emission contains pieces not accounted for by any cell"
        );
    }

    /// Compare the generator's emission for one cell (region shrunk 1e-6
    /// inside its unit square: the neighbours' box tests exclude them, so
    /// exactly the cell's four triangles are emitted, in triangle order)
    /// against the emitter's reference placement.
    fn check_ref(cell: (i8, i8), tile: u8, want: &[(u8, u32, [f64; 6]); 4], label: &str) {
        let p = ParamSet::default_for(JeandelRaoTiling.params());
        let (cx, cy) = cell;
        let c = cell_centre(usize::try_from(cx).unwrap(), usize::try_from(cy).unwrap());
        let eps = 1e-6;
        let r = JeandelRaoTiling.generate(
            &p,
            &Query {
                region: BBox::new(
                    Vec2::new(c.x - 0.5 + eps, c.y - 0.5 + eps),
                    Vec2::new(c.x + 0.5 - eps, c.y + 0.5 - eps),
                ),
            },
        );
        assert!(r.message.is_none(), "{label}: {:?}", r.message);
        assert_eq!(r.tiles.len(), 4, "{label}: triangle count");
        assert_eq!(
            PATCH[usize::try_from(cy).unwrap() * SIZE + usize::try_from(cx).unwrap()],
            tile,
            "{label}: tile id"
        );
        for (i, (got, w)) in r.tiles.iter().zip(want.iter()).enumerate() {
            assert_eq!(got.proto, w.0, "{label} triangle {i}: proto");
            assert_eq!(got.seed, w.1, "{label} triangle {i}: seed");
            assert_eq!(got.poly.pts.len(), 3, "{label} triangle {i}: vertex count");
            for (j, q) in got.poly.pts.iter().enumerate() {
                assert!(
                    (q.x - w.2[2 * j]).abs() < 1e-9 && (q.y - w.2[2 * j + 1]).abs() < 1e-9,
                    "{label} triangle {i} vertex {j}: ({}, {}) != ({}, {})",
                    q.x,
                    q.y,
                    w.2[2 * j],
                    w.2[2 * j + 1]
                );
            }
        }
    }

    /// The runtime reproduces the emitter's reference placements
    /// (float-eval check of the emitted tables against the JSON-derived
    /// model, same f64 expression order) and the seeds it predicts.
    #[test]
    fn jr_matches_generated_reference() {
        check_ref(REF0_CELL, REF0_TILE, &REF0, "REF0");
        check_ref(REF1_CELL, REF1_TILE, &REF1, "REF1");
    }
