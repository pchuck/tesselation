//! Hankin's method (Kaplan dissertation §3.4) — Hankin dodecagonal rosette (4.6.12).
//!
//! Constructed at runtime by the ported inference engine in
//! [`crate::hankin`]: rays from every substrate-edge midpoint at Kaplan
//! contact angle 60° to the edge, no truncation (single-point contacts, δ = 0), greedy min-cost
//! pairing (Kaplan §3.4: pairs sorted by total induced segment length),
//! then a planar arrangement of the paired segments against the tile
//! boundary gives the face partition. Template constants and the test
//! expectations in this file were machine-transcribed from the validated
//! 40-dps Python prototype (m94_emit.py); nothing hand-copied.
//!
//! Validation (Python battery, mpmath 40 dps, thresholds 1e-25):
//!   - pairing complete and tie-insensitive on every tile class,
//!   - face partition exact: |Σ faces − tile area| < 1e-25 per class,
//!   - planar patch: X-consistency at every valence-4 contact,
//!     400-point coverage probe exact,
//!   - torus (one-cell fold): valence {2:36, 4:18}, all strands close (12 strands of 12+12+12+12+12+12+12+12+12+12+12+12 segments),
//!   - symmetry probes: p6m confirmed exactly on the torus segment
//!     multiset.
//!
//! ## Configuration
//!
//! Substrate: truncated trihexagonal (4.6.12), dodecagon edge 1, lattice
//! s·⟨(1,0),(1/2,√3/2)⟩ with s = 3+√3 — dodecagon at the origin, squares
//! and hexagons at the dual positions. At θK = 60° every tile class pairs
//! completely into adjacent-edge rings: the dodecagon yields a 12-petal
//! rosette (13 faces), each square a 4-pointed star (5 faces), each
//! hexagon a 6-petal rosette (7 faces) — 42 faces per lattice cell.
//!
//! Distinct from the registered `pic-3-12-12` (θ = 45° reflection rule on
//! the 3.12.12 substrate): different substrate (4.6.12 vs 3.12.12) and
//! different construction (greedy inference vs reflection).
//!
//! Wallpaper group p6m (rot60 + mirror verified exactly on the torus
//! segment multiset).

